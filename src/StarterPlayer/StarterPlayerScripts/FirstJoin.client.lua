--[[
	FirstJoin -- the first two minutes of the game, guided (Phase 6.3, restyled 18.22 and 18.23).

	Zones 1 and 2 were designed as a tutorial stretch and then nothing ever told the player that.
	A new arrival landed in Forest with twenty-odd buttons, no idea that DNA comes from hitting the
	creatures walking past, and an EVOLVE button that says "not enough DNA" until they work out why.

	Three beats, and they are the roadmap's own: a camera pan that shows the street, an arrow that
	names the next thing to do, and the first evolve -- which `EvolveReveal` already celebrates, so
	this file gets out of the way rather than adding a second card on top of it. 18.23 added a
	fourth: the climb, which is the one thing in this world nobody finds on their own.

	What is on screen, end to end: a smooth camera pan over the starting Forest; a marching neon
	chevron trail on the ground running to the nearest live creature; a floating beacon and a
	Highlight on that creature; a pulsing halo and a bouncing arrow on the EVOLVE button when it is
	finally pressable; and one banner card carrying the step, its reason, and three progress pips.

	=========================================================================================
	WHAT DECIDES WHETHER THIS RUNS
	=========================================================================================
	`data.TutorialDone`, a real field in the save, flipped by the SERVER on the first evolve. Not
	"is this player at stage 1": a rebirth resets StageIndex to 1, so that test would replay the
	whole sequence for a veteran every time they reset. And not a client-side "I have finished"
	report, because a client that can say that can say it having never played.

	=========================================================================================
	THE THREE THINGS THAT WOULD LEAVE A PLAYER STUCK
	=========================================================================================
	1. A SCRIPTABLE CAMERA THAT IS NEVER GIVEN BACK. Everything the pan touches is restored in one
	   block that runs whether the pan finished, errored, or was skipped -- and the restore is the
	   `Custom` camera type plus the humanoid as subject, i.e. the state the engine sets up itself,
	   not a CFrame this file guessed. A failure halfway through otherwise leaves that player
	   looking at scenery with no way out but a rejoin.
	2. A GUIDE THAT WILL NOT LET GO. Any input at all skips the pan. Nobody who already knows this
	   game should have to watch three seconds of it, and a player who is pressing keys is telling
	   you exactly that.
	3. HEARTBEAT, NEVER RENDERSTEPPED. `RenderStepped:Wait()` never returns on a client that is not
	   rendering, and the whole sequence would hang inside its own pcall with no error anywhere --
	   see HatchReveal's header, which is where that cost an hour.

	=========================================================================================
	18.22 -- THE RESTYLE, AND WHAT THE "TUTORIAL BUILDER" PLUGIN ACTUALLY CONTRIBUTED
	=========================================================================================
	Asked for as *"dodala sam ti i tutorial builder u pluginovima, probaj to iskoristiti za tutorial
	da izgleda bolje, strelice i text i sve"*. The plugin (Tutorial Builder, @Jobble Games) was read
	rather than guessed at: its installed `Plugin.rbxm` was decompressed off disk and its single
	`TutorialMaker` script read end to end. Three things came out of that, and they decided the shape
	of this file.

	  1. IT HAD WRITTEN NOTHING. The plugin persists its step list to `ServerStorage.InGameTutorialData`
	     and exports a `StarterPlayerScripts.AutoGeneratedTutorialScript`. Neither instance exists in
	     this place -- the plugin is installed and has never been given a step. So there was no
	     authored content to import; there was only a FORMAT.
	  2. ITS OUTPUT COULD NOT BE USED AS-IS, and not merely on taste. The generated script is a
	     `Color3.fromRGB(20,20,20)` rectangle with no corner radius, no stroke and no gradient, set in
	     **Gotham** -- beside this game's FredokaOne-on-ink-outline surfaces it reads as a different
	     game's debug overlay. It is also ungated: it calls `showStep(1)` unconditionally on every
	     join for every player, with no equivalent of `TutorialDone`, so a veteran would be handed the
	     new-player wizard every single time they logged in. And its world arrow is a `Beam` textured
	     with `rbxassetid://15174447092`, which was probed live in this place and came back
	     **`IsLoaded = false`**, with `InsertService:LoadAsset` refusing it outright ("Asset is not
	     trusted for this place"). The plugin's arrows would have drawn nothing at all here.
	  3. ITS ONE GOOD IDEA WAS THE WORLD-SPACE TRAIL. A line of arrowheads marching from the player
	     toward the thing they are being told to go and hit is a genuinely better answer than a single
	     marker hanging over the target, because it is readable from behind, from the side, and while
	     you are running. That idea is taken. The Beam-plus-toolbox-texture MECHANISM is not, for the
	     measured reason above.

	So: the plugin's step SCHEMA (an ordered list of steps, each with text, an optional icon, and an
	optional named arrow target) is what `STEPS` below is shaped like, and every pixel of it is drawn
	with this game's own `CardKit` and `UITheme` instead of with the plugin's generator. The
	interaction model stays this file's rather than the plugin's: no "Next" button, because the step
	is DERIVED from the save every tick (see `stepFor`) and a player who evolves has already moved on
	without needing to dismiss anything.

	===== AND WHY THE CHEVRONS ARE GEOMETRY RATHER THAN A PICTURE =====

	Same argument the on-screen arrow below has always carried: an asset id is one more thing that can
	be moderated away or simply refused by the place, which is exactly what happened to the plugin's.
	`Enum.MeshType.Pyramid` is engine geometry -- it cannot fail to load, it needs no upload, and it
	orients along a CFrame, which a camera-facing glyph cannot do. Probed on this build before it was
	used.

	=========================================================================================
	A NOTE ON THIS FILE'S OWN HISTORY, BECAUSE IT IS THE POINT OF THE COMMENTS (19.6)
	=========================================================================================
	The 18.23 pass compacted this file from 915 lines to 674 and took 201 comment lines with it,
	leaving the header above as a five-line feature list. 19.0 established that the compacted copy
	was the DESCENDANT -- it holds real work (the sound cues, the halo, the vertical pips) -- so the
	restoration is a merge onto it rather than a revert, and every number quoted below was re-read
	off the code beside it rather than copied back from the old file.

	It was filed as documentation debt. It was not only that: the compaction also dropped two guards
	from `runClimbBeat`, and one of them is a live defect. See the block over that function.
--]]

