-- ============================================================================
-- THE CHEVRON TRAIL -- THE PLUGIN'S ONE GOOD IDEA, REBUILT (18.22)
-- ============================================================================
-- A line of arrowheads leaving the player's feet and running to whatever they are being told to go
-- and do. This is what the owner meant by *"strelice"*, and it is the half of the instruction the
-- old guide could not give: a marker floating over a creature tells you where it is only once you
-- have already found it, while a trail tells you which way to TURN.
--
-- WHY IT IS NOT THE PLUGIN'S BEAM. Tutorial Builder draws this with ten `Beam` objects textured
-- `rbxassetid://15174447092`. Probed in this place before anything was written: `IsLoaded = false`,
-- and `InsertService:LoadAsset` refuses it with "Asset is not trusted for this place". Ten
-- untextured beams is ten invisible ribbons -- the plugin's arrows would simply not have appeared.
-- `Enum.MeshType.Pyramid` is engine geometry: nothing to load, nothing to moderate, and it takes a
-- CFrame, so a chevron can actually POINT rather than being a camera-facing sprite that cannot.
--
-- EVERY PART IS LOCAL, ANCHORED AND UNTOUCHABLE, on exactly the terms `RarityBeam` sets out: with
-- `CanQuery` and `CanTouch` off, a chevron can never become the answer to a combat raycast, block a
-- player, or swallow a ProximityPrompt. They live in a client-made folder and replicate nowhere.
--
-- POOLED, NEVER CREATED PER FRAME. Eight parts are made once and moved; a trail that built and
-- destroyed its geometry on a Heartbeat would churn eight instances a frame for a picture that
-- barely changes.
local CHEVRON_COUNT = 8
local CHEVRON_GAP = 7          -- studs between arrowheads along the path
local CHEVRON_START = 9        -- how far in front of the player the first one sits
local CHEVRON_ARRIVED = 14     -- inside this range the trail switches off -- you have arrived
local CHEVRON_SPEED = 9        -- studs/sec the pattern scrolls toward the target

local trailFolder = Instance.new("Folder")
trailFolder.Name = "FirstJoinTrail"
trailFolder.Parent = workspace

local chevrons = {}
do
	for i = 1, CHEVRON_COUNT do
		local p = Instance.new("Part")
		p.Name = "Chevron" .. i
		p.Size = Vector3.new(3.2, 3.2, 3.2)
		p.Anchored = true
		p.CanCollide = false
		p.CanQuery = false
		p.CanTouch = false
		p.CastShadow = false
		p.Locked = true
		p.Material = Enum.Material.Neon
		p.Color = UITheme.Color.Sunny
		p.Transparency = 1
		-- Parented at the world origin would put eight glowing lumps in the middle of Forest for one
		-- frame; `RarityBeam`'s `scenery` note is about exactly this. Fully transparent from birth, so
		-- there is nothing to see until `updateTrail` has placed it.
		p.Parent = trailFolder

		local mesh = Instance.new("SpecialMesh")
		-- Guarded: `MeshType.Pyramid` was probed on this build, but this module is old enough to
		-- outlive a Studio version and a chevron that fails to become a pyramid should still be a
		-- glowing marker rather than an error that takes the whole guide down.
		local okMesh = pcall(function() mesh.MeshType = Enum.MeshType.Pyramid end)
		if not okMesh then
			mesh.MeshType = Enum.MeshType.Brick
		end
		mesh.Scale = Vector3.new(1, 1, 1)
		mesh.Parent = p

		chevrons[i] = p
	end
end

local function hideTrail()
	for _, p in ipairs(chevrons) do
		p.Transparency = 1
	end
end

-- `toPos` is where the player is being sent; nil switches the trail off. Called every tick from the
-- guide loop, so it does all its own no-op checks rather than making the caller branch.
local function updateTrail(toPos, tone)
	if trailSuspended or not toPos then
		hideTrail()
		return
	end
	local char = player.Character
	local root = char and char:FindFirstChild("HumanoidRootPart")
	if not root then
		hideTrail()
		return
	end

	local from = root.Position
	local flat = Vector3.new(toPos.X - from.X, 0, toPos.Z - from.Z)
	local dist = flat.Magnitude
	-- ARRIVED, or so close that a trail would be pointing through the player's own feet. Also the
	-- degenerate case: standing exactly on the target makes `flat.Unit` a NaN vector, which would
	-- write NaN CFrames and leave eight parts stuck at the origin until the next reparent.
	if dist < CHEVRON_ARRIVED then
		hideTrail()
		return
	end
	local dir = flat.Unit

	-- The pattern scrolls rather than the parts being re-spaced: each chevron's distance along the
	-- path is its index times the gap, plus a shared phase that advances with the clock and wraps at
	-- one gap. That is what makes it read as motion toward the target rather than as eight stationary
	-- markers -- and it costs one modulo instead of a per-part animation.
	local phase = (os.clock() * CHEVRON_SPEED) % CHEVRON_GAP
	for i, p in ipairs(chevrons) do
		local along = CHEVRON_START + (i - 1) * CHEVRON_GAP + phase
		if along >= dist - 2 then
			-- past the target: park it rather than drawing an arrow beyond the thing it points at
			p.Transparency = 1
		else
			local at = from + dir * along + Vector3.new(0, 3.4, 0)
			-- `CFrame.lookAt` puts -Z down the path and the pyramid's apex is +Y, so the mesh is
			-- tipped forward a quarter turn to make the point lead. Without the rotation every
			-- chevron is an arrow aimed at the sky.
			p.CFrame = CFrame.lookAt(at, at + dir) * CFrame.Angles(-math.pi / 2, 0, 0)
			-- Nearest is brightest and they fade with distance down the path, so the eye is pulled
			-- along the line in the direction of travel rather than seeing eight equal lumps.
			local fade = (i - 1) / CHEVRON_COUNT
			p.Transparency = 0.12 + fade * 0.55
			if tone then
				p.Color = tone
			end
		end
	end
end

-- `height` is how far above the target's own top the marker floats, so it clears a Swarmer and a
-- Guardian alike without being told how big either is.
local function pointAt(target, height)
	-- `trailSuspended` for the same reason `updateTrail` reads it, and this is the half that was
	-- missing. The panel watcher hides the guide by setting `gui.Enabled = false`, which governs
	-- GuiObjects -- and neither of these is one. A `BillboardGui` is its own LayerCollector and
	-- carries its own `Enabled`; a `Highlight` renders off its `Adornee` and does not care what it
	-- is parented to at all. So opening the Store left a creature outlined in yellow with a beacon
	-- bobbing over it, behind the panel the player had just opened.
	--
	-- Read HERE rather than in the watcher, because the guide loop calls `pointAt` every frame:
	-- anything the watcher switched off would be switched straight back on by the next tick.
	if trailSuspended or not target then
		marker.Enabled = false
		pointHL.Enabled = false
		pointHL.Adornee = nil
		marker.Adornee = nil
		return nil
	end
	local adornee = target
	if target:IsA("Model") then
		adornee = target.PrimaryPart or target:FindFirstChildWhichIsA("BasePart")
	end
	if not adornee then return nil end
	local _, size = pcall(function() return target:IsA("Model") and select(2, target:GetBoundingBox()) or target.Size end)
	local top = (typeof(size) == "Vector3" and size.Y or 6) * 0.5
	marker.Adornee = adornee
	-- 18.23: the marker BOBS, on its own sine rather than on a tween. A tween on a
	-- `StudsOffsetWorldSpace` would need one TweenService object per re-adorn, and this is re-adorned
	-- every frame onto a walking creature -- the arithmetic is free and cannot leak.
	marker.StudsOffsetWorldSpace = Vector3.new(0, top + (height or 5) + math.sin(os.clock() * 4) * 0.8, 0)
	marker.Enabled = true
	pointHL.Adornee = target
	pointHL.Enabled = true
	-- Handed back so the caller can feed the trail without resolving the target's position a second
	-- time -- the Model-vs-Part unwrap above is the fiddly half and doing it twice is how the two
	-- would drift apart.
	return adornee.Position
end

-- The nearest LIVE creature. Two traps, both already paid for elsewhere in this game and both silent
-- if ignored: `workspace.Creatures` holds loose `Part`s (`DeathBurst`) as well as rigs, so anything
-- that assumes a Model errors on a bare part; and a creature's health is a replicated ATTRIBUTE, not
-- a Humanoid -- asking for `Humanoid.Health` reports zero live creatures in a world holding hundreds,
-- which reads exactly like an empty street rather than like a wrong question.
local function nearestCreature()
	local char = player.Character
	local root = char and char:FindFirstChild("HumanoidRootPart")
	local folder = workspace:FindFirstChild("Creatures")
	if not root or not folder then return nil end
	local best, bestD = nil, 260
	for _, m in ipairs(folder:GetChildren()) do
		if m:IsA("Model") and (m:GetAttribute("Health") or 0) > 0 then
			local part = m.PrimaryPart
			if part then
				local d = (part.Position - root.Position).Magnitude
				if d < bestD then best, bestD = m, d end
			end
		end
	end
	return best
end

-- The nearest way UP. The flights live in `WorldShell` rather than in the zone folder, because
-- `TerraceRamp` is in ZoneBuilder's ALWAYS_LOADED set -- walkable ground that is allowed to stream
-- out is a hole to fall through. Looking for them in the zone finds nothing and looks exactly like
-- the ramps never having been built.
local function nearestRamp()
	local char = player.Character
	local root = char and char:FindFirstChild("HumanoidRootPart")
	local shell = workspace:FindFirstChild("WorldShell")
	if not root or not shell then return nil end
	local best, bestD = nil, 900
	for _, d in ipairs(shell:GetChildren()) do
		if d.Name == "TerraceRamp" then
			local dist = (d.Position - root.Position).Magnitude
			if dist < bestD then best, bestD = d, dist end
		end
	end
	return best
end

-- ============================================================================
-- WHAT THE PLAYER IS BEING ASKED TO DO
-- ============================================================================
-- Two steps, and which one is showing is derived from the save every tick rather than remembered.
-- A remembered step gets out of step with the world the first time something else moves the numbers
-- -- an offline payout, a code, a gift -- and then the guide is confidently wrong.
--
-- This is also the reason the plugin's model was not adopted wholesale. Tutorial Builder walks a
-- FIXED list with a "Next" button, which means the tutorial's idea of where you are and the save's
-- idea of where you are can disagree -- press Next twice and you are being told to evolve while the
-- server still says you cannot. Deriving it costs one function and cannot desynchronise.
local function stepFor(data)
	if not data then return nil end
	local step = GameConfig.GetEvolveStep(data)
	if step.isMax then return nil end
	-- XP alone, because XP alone is what the server checks now -- see DNAService.HandleEvolve. The
	-- DNA half of this test would have told a new player they were not ready while the button they
	-- are being pointed at was already green.
	if (data.XP or 0) >= step.xpCost then
		return "evolve"
	end
	return "fight"
end

-- Forward-declared: `runGuide` calls this and Lua binds an upvalue where a function is WRITTEN, so
-- without the name in scope here the call below would resolve to a nil global.
local runClimbBeat

local function runGuide()
	if state.running then return end
	state.running = true
	-- Repainted on every run rather than once at build time. The completion beat below repaints this
	-- card green and never puts it back, so a guide that ever restarts -- a player who quits
	-- mid-tutorial and returns in the same session -- would be given its instructions in the colour
	-- that means "finished". A one-way write to shared state is a bug waiting for a second caller.
	paintedKey = nil
	paintIfChanged("fight")

	task.spawn(function()
		local ok, err = pcall(function()
			local t0 = os.clock()
			while state.data and not state.data.TutorialDone do
				local which = stepFor(state.data)
				if which then
					banner.Visible = true
					paintIfChanged(which)
				else
					banner.Visible = false
				end

				-- the arrow belongs to the evolve step only: pointing at a button the player cannot
				-- press yet is an instruction to do something that will fail
				local btn = which == "evolve" and findEvolveButton() or nil
				if btn then
					local pos, size = btn.AbsolutePosition, btn.AbsoluteSize
					-- the bob runs along the axis it points down, so it reads as nudging the player
					-- toward the button rather than bouncing beside it
					local bob = math.abs(math.sin((os.clock() - t0) * 3.6)) * ARROW_BOB
					arrow.Position = UDim2.new(0, pos.X - 10 - bob, 0, pos.Y + size.Y * 0.5)
					arrow.Visible = true

					-- 18.23: the halo is re-fitted every frame from the same two live values, not
					-- placed once. The responsive pass at the bottom of MainUI resizes that button on
					-- any viewport change, and a ring sized at first sight would be left floating
					-- beside it -- worse than no ring, because it points at nothing.
					buttonHalo.Position = UDim2.new(0, pos.X - 4, 0, pos.Y - 4)
					buttonHalo.Size = UDim2.new(0, size.X + 8, 0, size.Y + 8)
					haloStroke.Transparency = 0.15 + 0.45 * math.abs(math.sin((os.clock() - t0) * 4))
					buttonHalo.Visible = true
				else
					arrow.Visible = false
					buttonHalo.Visible = false
				end

				-- AND THE OTHER HALF OF THE INSTRUCTION (9.10). "Click a creature" names the verb;
				-- the marker names the noun. Re-targeted every tick rather than locked on: the chosen
				-- creature is walking, can be killed by somebody else, and can stream out -- a guide
				-- pinned to one target ends up pointing at nothing and telling the player to hit it.
				--
				-- 18.22: and the trail is fed off the SAME resolved position, so the arrows on the
				-- ground and the marker in the air can never disagree about which creature is meant.
				if which == "fight" then
					local at = pointAt(nearestCreature(), 6)
					updateTrail(at, UITheme.Color.Sunny)
				else
					pointAt(nil)
					-- The evolve beat's target is a BUTTON, which is on the screen and not in the
					-- world: there is nowhere on the ground to send the player, so the trail stands
					-- down and the on-screen arrow carries that step alone.
					updateTrail(nil)
				end
				STEP:Wait()
			end
		end)

		banner.Visible = false
		arrow.Visible = false
		buttonHalo.Visible = false
		pointAt(nil)
		updateTrail(nil)
		state.running = false
		if not ok then
			warn("[FirstJoin] guide failed: " .. tostring(err))
		end

		-- The evolve itself is already celebrated by EvolveReveal's "New X Discovered!" card, so this
		-- adds one line rather than a second card: what to do NEXT, which is the one thing that card
		-- cannot say.
		if state.data and state.data.TutorialDone then
			-- FUNNEL STEP 6 (Phase 20). The guide is over: the evolve landed and this client got as
			-- far as showing the card that says so. Seconds after step 5 and deliberately so -- in
			-- this game the tutorial IS the first evolve, so the two steps are near-simultaneous by
			-- design and the interesting drop-off in this funnel is 4 -> 5, not 5 -> 6. The step is
			-- still worth having: it is the only one that proves a client reached the end of the
			-- sequence rather than the server having written the flag underneath it.
			pcall(function()
				local remotes = game:GetService("ReplicatedStorage"):FindFirstChild("Remotes")
				local step = remotes and remotes:FindFirstChild("TelemetryStep")
				if step then step:FireServer("tutorialDone") end
			end)
			paintIfChanged("done")
			banner.Visible = true
			task.delay(DONE_BANNER_TIME, function()
				banner.Visible = false
				runClimbBeat()
			end)
		end
	end)
end

-- ============================================================================
-- THE FOURTH BEAT: CLIMB (9.10)
-- ============================================================================
-- attack -> reward -> evolve are the first three and were already here. The row asks for a fourth,
-- and it is the one piece of this world nobody discovers on their own: the terraces carry the
-- stronger creatures and the shard drops, and the flights up them stand 400+ studs off the street.
-- A player who is never told looks at a valley and assumes that is the game.
--
-- SHOWN ONCE, AFTER THE EVOLVE, and driven by nothing that persists. There is no save field for it
-- and there should not be: a field means a migration and a repair for every existing save (6.3's
-- `TutorialDone` needed exactly that), for a banner that costs nothing if it is occasionally missed.
-- A session flag is the honest weight for a one-line hint.
--
-- 18.22: THIS IS THE BEAT THE TRAIL WAS BUILT FOR. A ramp is a fixed piece of geometry hundreds of
-- studs away and often behind the player -- the case where "look up there" is least useful and a
-- line of arrows on the ground is most. It is also why the trail is fed here on its own loop rather
-- than left adorned: the player is walking toward it, so the arrows have to be recomputed.
--
-- ===== BOTH GUARDS BELOW WERE DELETED BY THE 18.23 COMPACTION AND ARE RESTORED (19.6) =====
--
-- The `not ramp` one is the live defect. Without it this beat shows "Climb to the next terrace --
-- Tougher creatures, higher XP drops" for a full seven seconds WHEREVER the player happens to be,
-- and `pointAt(nil)` / `updateTrail(nil)` then correctly draw no marker and no trail -- so a player
-- in the arena or the Colosseum, neither of which has a terrace at all, is handed an instruction
-- with no target and no way to tell what it means. Saying nothing is the right answer when there is
-- no flight in range; pointing at the horizon is not.
--
-- The `climbShown` one is cheap insurance rather than an observed fault: today the only caller is
-- the `task.delay` in the completion branch above, and `onData` returns early once `TutorialDone`
-- is set, so it cannot currently fire twice. It is a one-shot hint and it should say so in its own
-- body rather than depend on that argument staying true.
runClimbBeat = function()
	if state.climbShown then return end
	state.climbShown = true
	local ramp = nearestRamp()
	-- No flight within range is a normal answer, not a failure: the arena and the Colosseum have
	-- no terraces at all. Say nothing rather than pointing at the horizon.
	if not ramp then return end
	paintIfChanged("climb")
	banner.Visible = true
	local t0 = os.clock()
	task.spawn(function()
		-- Re-resolved every tick rather than the single `ramp` above being reused: the player is
		-- walking toward it, the flights stream, and `pointAt` has to be called every frame anyway
		-- to survive the panel watcher (see its header). The lookup above is only the "is there one
		-- at all" question, which has to be answered before the banner is shown.
		while os.clock() - t0 < CLIMB_BEAT_TIME do
			local at = pointAt(nearestRamp(), 10)
			updateTrail(at, UITheme.Color.Aqua)
			STEP:Wait()
		end
		banner.Visible = false
		pointAt(nil)
		updateTrail(nil)
	end)
end

