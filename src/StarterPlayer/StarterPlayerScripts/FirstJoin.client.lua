-- Repaints the whole card for a step key. Cheap enough to call every tick, but only actually called
-- when the key CHANGES (see `paintIfChanged`) -- a gradient rewritten 60 times a second is 60 times
-- the garbage for an identical picture.
local function paint(key)
	local def = STEPS[key] or STEPS.fight
	setCardTone(def.tone)
	headline.Text = def.headline
	subline.Text = def.subline

	local asset = IconLibrary.Resolve(def.icon)
	if asset then
		iconImage.Image = asset
		iconImage.Visible = true
		iconGlyph.Visible = false
	else
		iconGlyph.Text = def.icon or ""
		iconGlyph.Visible = true
		iconImage.Visible = false
	end

	-- A pip is FILLED once its beat has been reached, so the column fills top to bottom as the player
	-- moves. `done` is not in `DOT_ORDER` and deliberately lights all three: it is the moment beat two
	-- completes, and a column that emptied itself on the celebration would read as progress lost.
	--
	-- 18.23: the CURRENT beat also takes `Color.Sunny` while the ones behind it stay white. Three
	-- filled pips say how far along you are; the amber one says which of them is being asked of you
	-- right now, which is the question the card's own text is answering.
	local reached = 0
	if key == "done" then
		reached = #DOT_ORDER
	else
		for i, name in ipairs(DOT_ORDER) do
			if name == key then
				reached = i
				break
			end
		end
	end
	for i, d in ipairs(dots) do
		d.BackgroundTransparency = (i <= reached) and 0 or 0.6
		d.BackgroundColor3 = (i == reached) and UITheme.Color.Sunny or CardKit.WHITE
	end
end

local paintedKey = nil
local function paintIfChanged(key)
	if key == paintedKey then return end
	paintedKey = key
	paint(key)
	-- 18.23: a cue on the two beats that are ACHIEVEMENTS, and on neither of the two that are
	-- instructions. "fight" and "climb" are things the player is being told to go and do, and a
	-- sound on an instruction is a nag; "evolve" (you have earned it) and "done" (you did it) are
	-- the two moments worth marking. Routed through SoundLibrary rather than a local Sound so it
	-- obeys the player's own audio settings -- see the Audio panel.
	if key == "evolve" or key == "done" then
		SoundLibrary.PlayLocal("levelUp", { volume = 0.45 })
	end
end

